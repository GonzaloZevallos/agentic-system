UNREADABLE = [{"job": "ci", "bytes": 0, "cause": "unreadable"}]


@dataclass
class _Context:
    ports: SimpleNamespace
    head: str = HEAD
    task_id: str = "GH-1"
    lines: list[str] = field(default_factory=list)

    def log(self, line: str) -> None:
        self.lines.append(line)


def _context(ci_logs: object) -> _Context:
    return _Context(ports=SimpleNamespace(ci_logs=ci_logs))


def _wrapper(context: _Context) -> tuple[str, list[dict[str, object]]]:
    text, records = landing_fix._ci_excerpt(cast(LandingContext, context), "ref")
    return text, [dict(record) for record in records]


def test_every_fixture_has_a_golden():
    assert {path.name for path in FIXTURES.glob("*.log")} == set(GOLDENS)


@pytest.mark.parametrize("name", sorted(GOLDENS))
def test_the_landing_excerpt_of_a_fixture_is_its_golden(name):
    digest, size, records = GOLDENS[name]
    context = _context(FakeCiLogs([fixture(name)]))

    text, got = _wrapper(context)

    assert hashlib.sha256(text.encode()).hexdigest() == digest
    assert len(text) == size
    assert got == records
    assert context.lines == []
    assert text.startswith(landing_fix.CI_LOG_NOTICE)


class _RaisingRead:
    def failed_job_logs(self, reference, head):
        raise OSError("gh is gone")


def test_a_raising_read_is_its_golden():
    context = _context(_RaisingRead())

    assert _wrapper(context) == ("", UNREADABLE)
    assert context.lines == ["agentic: land: GH-1: diagnose: CI logs not read (OSError)"]


def test_a_raising_render_is_its_golden(monkeypatch):
    def render(logs):
        raise KeyError("boom")

    monkeypatch.setattr(landing_rules, "ci_log_excerpt", render)
    context = _context(FakeCiLogs([fixture("check_test_failure.log")]))

