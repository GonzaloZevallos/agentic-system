"""GH-603 end to end, on real repositories: in docs `validate` mode a branch whose generated docs
are stale passes the delivery gate and the delivered head keeps no owned path differing from
master's merge-base; a conflict confined to the owned paths merges settled from master's side.
`commit` mode leaves the branch's generated files alone."""

from __future__ import annotations

import subprocess
from pathlib import Path

import pytest

from agentic.core.process.adapters.git import GitWorkspace
from agentic.core.process.application import docs_settlement
from agentic.core.process.application.presubmit import CheckoutPresubmit
from agentic.core.process.domain.check_schedule import CheckPriority
from agentic.core.process.domain.docs import Docs
from agentic.shared.configuration import Configuration
from tests.fakes import FakeCheckScheduler, MemoryCommands, MemoryStack

IDENTITY = Configuration(product_dir=Path("/tmp/p")).git_identity
VALIDATE = Docs("make docs", ("docs/gen/**",), mode="validate")
COMMIT = Docs("make docs", ("docs/gen/**",))


def git(*args: str, cwd: Path) -> str:
    return subprocess.run(
        ["git", "-c", "user.name=t", "-c", "user.email=t@t", *args],
        cwd=cwd,
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()


def commit(root: Path, relative: str, text: str, message: str) -> str:
    target = root / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text)
    git("add", "-A", cwd=root)
    git("commit", "-qm", message, cwd=root)
    return git("rev-parse", "HEAD", cwd=root)


@pytest.fixture
def repo(tmp_path: Path) -> Path:
    """A product with an origin: master holds `docs/gen/a.md` and `app/code.py`."""
    origin = tmp_path / "origin.git"
    git("init", "-q", "--bare", "-b", "master", str(origin), cwd=tmp_path)
    root = tmp_path / "product"
    root.mkdir()
    git("init", "-q", "-b", "master", cwd=root)
    git("remote", "add", "origin", str(origin), cwd=root)
    commit(root, "docs/gen/a.md", "base\n", "base")
    commit(root, "app/code.py", "base\n", "code")
    git("push", "-q", "origin", "master", cwd=root)
    return root


def _diff_owned(root: Path, head: str, tip: str) -> str:
    base = git("merge-base", head, tip, cwd=root)
    return git("diff", "--name-only", base, head, "--", ":(glob)docs/gen/**", cwd=root)


def _gate(root: Path, docs: Docs, before: str) -> CheckoutPresubmit:
    ports = type(
        "Ports",
        (),
        {
            "workspace": GitWorkspace(root, IDENTITY),
            "commands": MemoryCommands(),
            "check_scheduler": FakeCheckScheduler(),
            "stack": MemoryStack(docs=docs),
        },
    )()
    return CheckoutPresubmit(
        ports, root, before, {"tests": "pytest"}, 30.0, priority=CheckPriority.SUBTASK, docs=docs
    )


def _stale_branch(repo: Path) -> tuple[str, str]:
    """`feature` commits code and a regenerated doc while master moves on and regenerates it
    too (and is pushed). Returns `(base, master_tip)`."""
    base = git("rev-parse", "HEAD", cwd=repo)
    git("checkout", "-q", "-b", "feature", cwd=repo)
    commit(repo, "app/code.py", "feature\n", "feature work")
    commit(repo, "docs/gen/a.md", "stale regenerated\n", "regenerated by the branch")
    commit(repo, "docs/gen/new.md", "new\n", "a new generated page")
    git("checkout", "-q", "master", cwd=repo)
    tip = commit(repo, "docs/gen/a.md", "master regenerated\n", "master regenerates")
    git("push", "-q", "origin", "master", cwd=repo)
    git("checkout", "-q", "feature", cwd=repo)
    return base, tip


def test_a_stale_branch_passes_and_the_delivered_head_keeps_no_owned_drift(repo):
    base, tip = _stale_branch(repo)
    before = git("rev-parse", "--short", base, cwd=repo)
    assert _diff_owned(repo, "HEAD", tip) != ""  # the branch really did commit generated files

    gate = _gate(repo, VALIDATE, before)

    assert gate() is None
    assert _diff_owned(repo, "HEAD", tip) == ""
    assert (repo / "app/code.py").read_text() == "feature\n"  # its own work stays
    assert not (repo / "docs/gen/new.md").exists()
    assert git("status", "--porcelain", cwd=repo) == ""
    assert "docs/gen/a.md" in (gate.markdown() or "")


def test_commit_mode_leaves_the_branchs_generated_files_alone(repo):
    base, tip = _stale_branch(repo)
    head = git("rev-parse", "HEAD", cwd=repo)

    assert _gate(repo, COMMIT, git("rev-parse", "--short", base, cwd=repo))() is None

    assert git("rev-parse", "HEAD", cwd=repo) == head
    assert (repo / "docs/gen/new.md").exists()


def test_a_conflict_only_in_owned_paths_merges_settled_from_masters_side(repo):
    workspace = GitWorkspace(repo, IDENTITY)
    git("checkout", "-q", "-b", "subtask", cwd=repo)
    commit(repo, "docs/gen/a.md", "subtask regenerated\n", "subtask")
    git("checkout", "-q", "master", cwd=repo)
    commit(repo, "docs/gen/a.md", "master regenerated\n", "master regenerates")
    git("push", "-q", "origin", "master", cwd=repo)
    git("checkout", "-q", "-b", "task", cwd=repo)
    commit(repo, "docs/gen/a.md", "task regenerated\n", "task")

    refusal = workspace.merge(repo, "subtask")
    assert refusal is not None
    merged = docs_settlement.settle_refused_merge(workspace, repo, "subtask", VALIDATE, refusal)

    assert merged
    assert git("status", "--porcelain", cwd=repo) == ""
    assert not (repo / ".git" / "MERGE_HEAD").exists()  # no merge is left open
    assert (repo / "docs/gen/a.md").read_text() == "master regenerated\n"
    assert git("merge-base", "--is-ancestor", "subtask", "HEAD", cwd=repo) == ""


def test_a_mixed_conflict_is_refused_and_leaves_the_tree_clean(repo):
    workspace = GitWorkspace(repo, IDENTITY)
    git("checkout", "-q", "-b", "subtask", cwd=repo)
    commit(repo, "docs/gen/a.md", "subtask\n", "subtask docs")
    commit(repo, "app/code.py", "subtask\n", "subtask code")
    git("checkout", "-q", "master", cwd=repo)
    git("checkout", "-q", "-b", "task", cwd=repo)
    commit(repo, "docs/gen/a.md", "task\n", "task docs")
    commit(repo, "app/code.py", "task\n", "task code")
    git("push", "-q", "origin", "master", cwd=repo)

    refusal = workspace.merge(repo, "subtask")
    assert refusal is not None
    merged = docs_settlement.settle_refused_merge(workspace, repo, "subtask", VALIDATE, refusal)

    assert not merged
    assert git("status", "--porcelain", cwd=repo) == ""
