"""The size budget of a task: how much hand-written code one pull request may carry.

A task is sized to merge within hours (owner's rule, issue #592): it may declare at most
`HAND_FILES` hand-written non-test files and `HAND_LINES` added hand-written non-test lines,
and its tests have their own cap, `TEST_LINES` added lines. A path the product declares as
generated never counts. This module is the only place those limits, the rule that tells a hand
file from a test or a generated one, and the shape of the planned and the actual size record
are written; `rules.estimate_fits` is the single entry point that compares a plan against them.

Pure: no I/O, no stack, no git. Whoever reads the stack at the task's base commit hands the
generated globs in, and whoever runs git hands the `NumstatRow`s in.
"""

from __future__ import annotations

import math
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from typing import Literal

from agentic.core.process.domain.master_gain import matches

HAND_FILES = 15
HAND_LINES = 400
TEST_LINES = 600
# The old `SPLIT_FILES`: the only limit a plan written before the size fields is judged by.
LEGACY_FILES = 40
# The floor on the declared hand-written size while the history is short (ADR of GH-592): the
# factor until `PROVEN_PAIRS` closed tasks carry both figures, then the p90 of the real ratio.
UNPROVEN_RATIO = 1.5
PROVEN_PAIRS = 10
# The floor factor: one figure for both fields, or `(files, lines)` once the history proves them.
Ratio = float | tuple[float, float]

# Basenames of the lockfiles: generated by a package manager whatever the product declares.
LOCKFILES = (
    "uv.lock",
    "poetry.lock",
    "Pipfile.lock",
    "package-lock.json",
    "npm-shrinkwrap.json",
    "pnpm-lock.yaml",
    "yarn.lock",
    "bun.lockb",
    "Cargo.lock",
    "go.sum",
    "Gemfile.lock",
    "composer.lock",
)
TEST_DIRECTORIES = ("tests", "test", "__tests__", "e2e")
TEST_NAMES = ("test_*", "*_test.*", "*.test.*", "*.spec.*")

# The frontmatter keys that hold the record, and the fields of each.
PLANNED_KEY = "planned_size"
ACTUAL_KEY = "actual_size"
HAND_FILES_FIELD = "hand_files"
HAND_LINES_FIELD = "hand_lines"
TEST_LINES_FIELD = "test_lines"
GENERATED_FILES_FIELD = "generated_files"

PathKind = Literal["hand", "test", "generated"]


@dataclass(frozen=True)
class NumstatRow:
    """One row of `git diff --numstat`: the path (the new one for a rename) and the lines
    added and deleted, 0 and 0 for a binary file or a pure rename."""

    path: str
    added: int
    deleted: int


@dataclass(frozen=True)
class PlanSize:
    """The size a plan declares: hand-written non-test files and added lines, and test lines."""

    hand_files: int
    hand_lines: int
    test_lines: int

    def to_frontmatter(self) -> dict[str, dict[str, int]]:
        """The one-key mapping a task document stores the record under."""
        return {
            PLANNED_KEY: {
                HAND_FILES_FIELD: self.hand_files,
                HAND_LINES_FIELD: self.hand_lines,
                TEST_LINES_FIELD: self.test_lines,
            }
        }

    @staticmethod
    def from_frontmatter(frontmatter: Mapping[str, object]) -> PlanSize | None:
        """The record a document holds under `planned_size`, or None when it is absent or
        not a mapping of non-negative integers: a document older than the field."""
        found = _fields(
            frontmatter.get(PLANNED_KEY), (HAND_FILES_FIELD, HAND_LINES_FIELD, TEST_LINES_FIELD)
        )
        if found is None:
            return None
        return PlanSize(found[0], found[1], found[2])


@dataclass(frozen=True)
class ActualSize:
    """The size a delivery measured: the same three figures, plus how many generated files
    it carried (reported, never counted against the budget)."""

    hand_files: int
    hand_lines: int
    test_lines: int
    generated_files: int

    def to_frontmatter(self) -> dict[str, dict[str, int]]:
        """The one-key mapping a task document stores the record under."""
        return {
            ACTUAL_KEY: {
                HAND_FILES_FIELD: self.hand_files,
                HAND_LINES_FIELD: self.hand_lines,
                TEST_LINES_FIELD: self.test_lines,
                GENERATED_FILES_FIELD: self.generated_files,
            }
        }

    @staticmethod
    def from_frontmatter(frontmatter: Mapping[str, object]) -> ActualSize | None:
        """The record a document holds under `actual_size`, or None when it is absent or
        not a mapping of non-negative integers."""
        found = _fields(
            frontmatter.get(ACTUAL_KEY),
            (HAND_FILES_FIELD, HAND_LINES_FIELD, TEST_LINES_FIELD, GENERATED_FILES_FIELD),
        )
        if found is None:
            return None
        return ActualSize(found[0], found[1], found[2], found[3])


@dataclass(frozen=True)
class Divergence:
    """Actual over planned, per field; None where the plan said 0, which has no ratio."""

    hand_files: float | None
    hand_lines: float | None
    test_lines: float | None


def classify(path: str, generated_globs: Sequence[str]) -> PathKind:
    """What a path is for the budget: `generated` when its basename is a lockfile or it
    matches one of the product's generated globs; else `test` by directory or file name;
    everything else, docs and prompts included, is `hand`."""
    segments = [part for part in path.split("/") if part]
    name = segments[-1] if segments else path
    if name in LOCKFILES or any(matches(glob, path) for glob in generated_globs):
        return "generated"
    if any(part in TEST_DIRECTORIES for part in segments[:-1]):
        return "test"
    if any(matches(pattern, name) for pattern in TEST_NAMES):
        return "test"
    return "hand"


def measure(rows: Sequence[NumstatRow], generated_globs: Sequence[str]) -> ActualSize:
    """The actual size of a delivery. A row with no added and no deleted line (a pure rename,
    a binary file) is free for hand and test files; a generated file is always reported."""
    hand_files = hand_lines = test_lines = generated_files = 0
    for row in rows:
        kind = classify(row.path, generated_globs)
        if kind == "generated":
            generated_files += 1
        elif row.added == 0 and row.deleted == 0:
            continue
        elif kind == "test":
            test_lines += row.added
        else:
            hand_files += 1
            hand_lines += row.added
    return ActualSize(hand_files, hand_lines, test_lines, generated_files)


def judged(size: PlanSize, ratio: Ratio = UNPROVEN_RATIO) -> PlanSize:
    """The declared figures as the budget judges them: hand-written files and lines times the
    floor `ratio`, rounded up, test lines as declared (the floor raises, it never refuses)."""
    files, lines = _pair(ratio)
    return PlanSize(
        _scaled(size.hand_files, files), _scaled(size.hand_lines, lines), size.test_lines
    )


def crossed(size: PlanSize) -> tuple[str, ...]:
    """The fields of `size` over their cap, by the name the record stores them under."""
    over = (
        (HAND_FILES_FIELD, size.hand_files > HAND_FILES),
        (HAND_LINES_FIELD, size.hand_lines > HAND_LINES),
        (TEST_LINES_FIELD, size.test_lines > TEST_LINES),
    )
    return tuple(name for name, is_over in over if is_over)


def fits(size: PlanSize) -> bool:
    """Whether the figures are within the three caps. The floor factor is the caller's."""
    return not crossed(size)


def legacy_fits(files: int) -> bool:
    """Whether a plan with no size fields is within the one file limit it is judged by."""
    return files <= LEGACY_FILES


def divergence(planned: PlanSize, actual: ActualSize) -> Divergence:
    """How far the delivery went from the plan, per field, as actual / planned."""
    return Divergence(
        _ratio(actual.hand_files, planned.hand_files),
        _ratio(actual.hand_lines, planned.hand_lines),
        _ratio(actual.test_lines, planned.test_lines),
    )


def budget_text(ratio: Ratio | None) -> str:
    """The paragraph the planner reads, every number from the constants above. With a
    `ratio`, it says the declared hand-written files and lines are judged times it (one
    figure for both, or each its own once the history proves them)."""
    text = (
        f"Size budget: a task may declare at most {HAND_FILES} hand-written non-test files and "
        f"{HAND_LINES} added hand-written non-test lines. Tests have their own cap of "
        f"{TEST_LINES} added lines. A path is a test when a directory of it is one of "
        f"{_names(TEST_DIRECTORIES)} or its file name matches {_names(TEST_NAMES)}. Generated "
        f"paths never count: the lockfiles ({_names(LOCKFILES)}), the stack's `docs.paths` and "
        "its `generated:` globs. Docs, ADRs, README and prompt files are hand-written."
    )
    if ratio is not None:
        files, lines = _pair(ratio)
        factor = f"x {files:g}" if files == lines else f"x {files:g} files and x {lines:g} lines"
        text += (
            f" The declared hand-written files and lines are judged {factor}, rounded up, "
            "so declare them as honestly as you can."
        )
    return text


def _names(names: Sequence[str]) -> str:
    return ", ".join(f"`{name}`" for name in names)


def _pair(ratio: Ratio) -> tuple[float, float]:
    return (ratio, ratio) if isinstance(ratio, float | int) else ratio


def _scaled(figure: int, ratio: float) -> int:
    # Rounded to 9 places first, so a float product that lands a hair over a whole number
    # (2.0000000000000004) is not pushed to the next one by the ceiling.
    return math.ceil(round(figure * ratio, 9))


def _ratio(actual: int, planned: int) -> float | None:
    return actual / planned if planned else None


def _fields(found: object, names: tuple[str, ...]) -> tuple[int, ...] | None:
    if not isinstance(found, Mapping):
        return None
    values = [found.get(name) for name in names]
    if not all(
        isinstance(value, int) and not isinstance(value, bool) and value >= 0 for value in values
    ):
        return None
    return tuple(value for value in values if isinstance(value, int))
